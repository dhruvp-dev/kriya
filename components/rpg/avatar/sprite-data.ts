/**
 * Palette Index Conventions for 32x32 Pixel Art Avatars:
 * 0 = Transparent
 * 1 = Skin Tone (#fbcfe8 or #fed7aa)
 * 2 = Primary Tint (Swappable main color e.g., armor, robe, tunic)
 * 3 = Primary Tint Dark (Shade version of primary tint, auto-calculated or preset)
 * 4 = Dark Outline / Shadow (#0f172a)
 * 5 = Hair (#374151 or #78350f)
 * 6 = Secondary Cloth / Pants (#334155)
 * 7 = Metal / Accent / Gold (#f59e0b or #cbd5e1)
 * 8 = Leather Boots / Belt (#78350f)
 * 9 = Eye / Facial Detail (#020617)
 */

export type PixelGrid = number[][];

// Helper to convert 32 rows of 32-char strings into 32x32 number matrix
function parseSprite(rows: string[]): PixelGrid {
  if (rows.length !== 32) {
    throw new Error(`Sprite must have exactly 32 rows, got ${rows.length}`);
  }
  return rows.map((row, rIdx) => {
    if (row.length !== 32) {
      throw new Error(`Row ${rIdx} must have exactly 32 columns, got ${row.length}`);
    }
    return row.split('').map((ch) => parseInt(ch, 10));
  });
}

