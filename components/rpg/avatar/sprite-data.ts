// --- ACCESSORY SPRITES OVERLAYS ---

export interface AccessoryOverlay {
  grid: PixelGrid;
  offsetX: number;
  offsetY: number;
}

// Helper to make blank 32x32 overlay with rows
function makeOverlay(rows: string[], offsetX = 0, offsetY = 0): AccessoryOverlay {
  return {
    grid: parseSprite(rows),
    offsetX,
    offsetY,
  };
}

